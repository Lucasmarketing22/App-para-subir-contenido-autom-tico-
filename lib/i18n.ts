export function translate(lang: string, key: I18nKey, vars?: Record<string, string | number>): string {
  let str = (DICTS[lang] ?? es)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, String(v));
  return str;
}
